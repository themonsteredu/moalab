-- -------------------------------------------- 갈래마다 표(칸 12개) 붙이기
--  ★ **이미 표가 있는 역할은 건드리지 않습니다** (not exists).
--    원장님이 손으로 만든 칸을 덮어쓰면 적어둔 값이 같이 사라집니다.
--
--  · 첫 칸이 **줄의 제목**입니다 — 폰에서는 줄 하나가 카드로 그려집니다
--  · 첫 `고르기` 칸이 **오른쪽 상태 칩**이 됩니다 → 그래서 `진행 상태` 를 앞에 뒀습니다
--  · `지역` 을 고르기로 둔 이유: 글로 적으면 `광주 북구` 와 `북구` 가 따로 셉니다
insert into moalab.duty_columns (duty_id, name, kind, options, sort_order)
select du.id, c.name, c.kind, c.options::jsonb, c.ord
from moalab.duties du
join moalab.duty_groups gr on gr.id = du.group_id
join moalab.departments d  on d.id  = gr.dept_id
cross join (values
  ('기관 이름',        'text',   null::text, 1),
  ('진행 상태',        'select',
     '["연락 전","연락함","제안서 보냄","미팅","견적·계약","진행 중","완료","보류"]', 2),
  ('지역',             'select',
     '["광주 동구","광주 서구","광주 남구","광주 북구","광주 광산구",
       "목포시","여수시","순천시","나주시","광양시",
       "담양군","곡성군","구례군","고흥군","보성군","화순군","장흥군","강진군",
       "해남군","영암군","무안군","함평군","영광군","장성군","완도군","진도군","신안군",
       "그 밖"]', 3),
  ('담당자·부서',      'text',   null::text, 4),
  ('연락처',           'text',   null::text, 5),
  ('이메일·홈페이지',  'text',   null::text, 6),
  ('관심 프로그램',    'text',   null::text, 7),
  ('예상 인원',        'number', null::text, 8),
  ('예상 금액',        'number', null::text, 9),
  ('다음 할 일',       'text',   null::text, 10),
  ('다음 연락일',      'date',   null::text, 11),
  ('메모',             'text',   null::text, 12)
) as c(name, kind, options, ord)
where d.name = '영업마케팅부'
  and gr.name like '신규발굴%'
  and not exists (select 1 from moalab.duty_columns x where x.duty_id = du.id);

-- ------------------------------------------------------------- 확인
--  중분류 5줄이 각각 소분류 개수와 함께 나오면 성공입니다.
select gr.name as 중분류, count(distinct du.id) as 소분류, count(dc.id) as 표칸
from moalab.duty_groups gr
join moalab.departments d on d.id = gr.dept_id
left join moalab.duties du on du.group_id = gr.id
left join moalab.duty_columns dc on dc.duty_id = du.id
where d.name = '영업마케팅부' and gr.name like '신규발굴%'
group by gr.name, gr.sort_order
order by gr.sort_order;

