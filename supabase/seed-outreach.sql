-- ------------------------------------------------------------ 부서
-- 이미 있으면 그대로 둡니다 (sort_order 도 안 건드립니다).
insert into moalab.departments (name, sort_order) values ('영업마케팅부', 2)
on conflict (name) do nothing;

-- -------------------------------------------------------- 중분류 5
--  기존 중분류(학교·기관 영업 1 · 홍보 2 · 고객 관리 3) 뒤에 오도록 11부터.
insert into moalab.duty_groups (dept_id, name, sort_order)
select d.id, g.name, g.ord
from moalab.departments d
join (values
  ('영업마케팅부', '신규발굴 학교',           11),
  ('영업마케팅부', '신규발굴 청소년기관',     12),
  ('영업마케팅부', '신규발굴 아동·돌봄',      13),
  ('영업마케팅부', '신규발굴 청년·대학',      14),
  ('영업마케팅부', '신규발굴 공공·문화·복지', 15)
) as g(dept, name, ord) on g.dept = d.name
on conflict (dept_id, name) do nothing;

-- ------------------------------------------------------- 소분류 15
--  소분류 하나 = 기관 갈래 하나 = **표 하나**. 갈래마다 파는 말이 다르기 때문에
