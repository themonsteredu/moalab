select d.name as 부서, count(distinct g.id) as 중분류, count(t.id) as 소분류
from moalab.departments d
left join moalab.duty_groups g on g.dept_id = d.id
left join moalab.duties t on t.group_id = g.id
group by d.name, d.sort_order
order by d.sort_order;
